import io
import json
import os

try:
    from hatchling.builders.hooks.plugin.interface import BuildHookInterface
except ImportError:
    BuildHookInterface = object


class EmojiDbBuildHook(BuildHookInterface):
    def initialize(self, version, build_data):
        root = os.path.dirname(os.path.abspath(__file__))
        outfile = os.path.join(root, "emoji_fzf/emoji_fzf_emojilib.py")
        _generate_emoji_db(root, outfile)


def _generate_emoji_db(root_dir, outfile):
    emoji_dict = _get_gemoji_db_data(root_dir)

    with io.open(
        os.path.join(root_dir, "emojilib/dist/emoji-en-US.json"), "rt", encoding="utf8"
    ) as f:
        emojilib = json.load(f)

    emojilib_by_codepoint = {cp: tuple(aliases) for cp, aliases in emojilib.items()}

    for key, val in emoji_dict.items():
        extra = emojilib_by_codepoint.pop(val["emoji"], ())
        emoji_dict[key]["aliases"] = tuple(set(val["aliases"] + extra))

    for codepoint, (name, *aliases) in emojilib_by_codepoint.items():
        emoji_dict[name.replace(" ", "_")] = {"emoji": codepoint, "aliases": tuple(aliases)}

    _raw_emoji_list_update(root_dir, emoji_dict)

    with open(outfile, "w", encoding="utf-8") as f:
        f.write('# -*- coding: utf-8 -*-\n"""\nEmoji python alias file, autogenerated.\n"""\n\n')
        f.write("EMOJIS = {}".format(emoji_dict))


def _get_gemoji_db_data(root_dir):
    with io.open(os.path.join(root_dir, "gemoji/db/emoji.json"), "rt", encoding="utf8") as f:
        data = json.load(f)
    return {
        "_".join(e["description"].split()): {
            "emoji": e["emoji"],
            "aliases": tuple(e["aliases"]),
        }
        for e in data
    }


def _raw_emoji_list_update(root_dir, emoji_dict):
    with io.open(
        os.path.join(root_dir, "unicode-emoji-json/data-by-emoji.json"), "rt", encoding="utf8"
    ) as f:
        data = json.load(f)
    for emoji, value in data.items():
        slug = value["slug"]
        if slug not in emoji_dict:
            emoji_dict[slug] = {"emoji": emoji, "aliases": ()}


if __name__ == "__main__":
    root = os.path.dirname(os.path.abspath(__file__))
    _generate_emoji_db(root, os.path.join(root, "emoji_fzf/emoji_fzf_emojilib.py"))
    print("Generated emoji_fzf/emoji_fzf_emojilib.py")
