"""Hatch build hook that generates the emoji database at build time."""

import io
import json
import os
import re
import urllib.error
import urllib.request

try:
    from hatchling.builders.hooks.plugin.interface import BuildHookInterface
except ImportError:
    BuildHookInterface = object


class EmojiDbBuildHook(BuildHookInterface):  # pylint: disable=too-few-public-methods
    """Hatch build hook that generates the emoji database module."""

    def initialize(self, _version, build_data):
        """Generate the emoji database before building."""
        root_dir = os.path.dirname(os.path.abspath(__file__))
        outfile = os.path.join(root_dir, "emoji_fzf/emoji_fzf_emojilib.py")
        _generate_emoji_db(root_dir, outfile)
        build_data["force_include"][outfile] = "emoji_fzf/emoji_fzf_emojilib.py"


def _generate_emoji_db(root_dir, outfile):
    emoji_dict = _get_gemoji_db_data(root_dir)

    with io.open(
        os.path.join(root_dir, "emojilib/dist/emoji-en-US.json"), "rt", encoding="utf8"
    ) as fp:
        emojilib = json.load(fp)

    emojilib_by_codepoint = {cp: tuple(aliases) for cp, aliases in emojilib.items()}

    for key, val in emoji_dict.items():
        extra = emojilib_by_codepoint.pop(val["emoji"], ())
        emoji_dict[key]["aliases"] = tuple(set(val["aliases"] + extra))

    for codepoint, (name, *aliases) in emojilib_by_codepoint.items():
        emoji_dict[name.replace(" ", "_")] = {"emoji": codepoint, "aliases": tuple(aliases)}

    _raw_emoji_list_update(root_dir, emoji_dict)
    _unicode_draft_update(emoji_dict)

    with open(outfile, "w", encoding="utf-8") as fp:
        fp.write('# -*- coding: utf-8 -*-\n"""\nEmoji python alias file, autogenerated.\n"""\n\n')
        fp.write("EMOJIS = {}".format(emoji_dict))


def _get_gemoji_db_data(root_dir):
    with io.open(os.path.join(root_dir, "gemoji/db/emoji.json"), "rt", encoding="utf8") as fp:
        data = json.load(fp)
    return {
        "_".join(e["description"].split()): {
            "emoji": e["emoji"],
            "aliases": tuple(e["aliases"]),
        }
        for e in data
    }


def _raw_emoji_list_update(root_dir, emoji_dict):
    with io.open(
        os.path.join(root_dir, "unicode-emoji-json/data-by-emoji.json"), "rt", encoding="utf8"
    ) as fp:
        data = json.load(fp)
    for emoji, value in data.items():
        slug = value["slug"]
        if slug not in emoji_dict:
            emoji_dict[slug] = {"emoji": emoji, "aliases": ()}


_UNICODE_DRAFT_URL = "https://www.unicode.org/Public/draft/emoji/emoji-test.txt"
# Matches: "1F600 ; fully-qualified # 😀 E1.0 grinning face"
_EMOJI_TEST_RE = re.compile(r"^[\dA-F ]+;\s*fully-qualified\s*#\s*(\S+)\s+E[\d.]+\s+(.+)$")


def _unicode_draft_update(emoji_dict):
    """Add fully-qualified emojis from the Unicode draft that aren't in any other source."""
    try:
        with urllib.request.urlopen(_UNICODE_DRAFT_URL, timeout=10) as resp:
            text = resp.read().decode("utf-8")
    except (OSError, urllib.error.URLError) as exc:
        print("Warning: could not fetch Unicode draft emoji list: {}".format(exc))
        return

    existing_codepoints = {v["emoji"] for v in emoji_dict.values()}
    added = 0
    for line in text.splitlines():
        match = _EMOJI_TEST_RE.match(line)
        if not match:
            continue
        emoji, name = match.group(1), match.group(2)
        if emoji in existing_codepoints:
            continue
        slug = name.lower().replace(" ", "_").replace(":", "").replace(",", "")
        emoji_dict[slug] = {"emoji": emoji, "aliases": ()}
        existing_codepoints.add(emoji)
        added += 1
    if added:
        print("Added {} emoji(s) from Unicode draft".format(added))


if __name__ == "__main__":
    root = os.path.dirname(os.path.abspath(__file__))
    _generate_emoji_db(root, os.path.join(root, "emoji_fzf/emoji_fzf_emojilib.py"))
    print("Generated emoji_fzf/emoji_fzf_emojilib.py")
